// Export formats: Markdown (review + references), BibTeX, RIS, JSON.

const included = (s) => (s.papers || []).filter((p) => p.included).sort((a, b) => a.n - b.n);

function citeKey(p, used) {
  const last = String((p.authors && p.authors[0]) || 'anon').trim().split(/\s+/).pop().toLowerCase().normalize('NFKD').replace(/[^a-z]/g, '') || 'anon';
  const word = String(p.title || '').toLowerCase().split(/\s+/).find((w) => w.length > 3 && !['with', 'from', 'that', 'this', 'into', 'over', 'towards'].includes(w)) || 'paper';
  let key = `${last}${p.year || ''}${word.replace(/[^a-z]/g, '')}`;
  let k = key, i = 1;
  while (used.has(k)) k = key + String.fromCharCode(96 + ++i);
  used.add(k);
  return k;
}

const bibEsc = (s) => String(s || '').replace(/([{}&%$#_])/g, '\\$1');

export function toBibtex(s) {
  const used = new Set();
  return included(s).map((p) => {
    const isPreprint = /arxiv|preprint/i.test((p.venue || '') + (p.kind || ''));
    const fields = [
      ['title', `{${bibEsc(p.title)}}`],
      ['author', bibEsc((p.authors || []).join(' and '))],
      ['year', p.year],
      [isPreprint ? 'howpublished' : 'journal', bibEsc(p.venue)],
      ['doi', p.doi && !/arxiv/i.test(p.doi) ? p.doi : ''],
      ['eprint', p.ids && p.ids.arxiv],
      ['archivePrefix', p.ids && p.ids.arxiv ? 'arXiv' : ''],
      ['url', p.url],
    ].filter(([, v]) => v);
    return `@${isPreprint ? 'misc' : 'article'}{${citeKey(p, used)},\n${fields.map(([k, v]) => `  ${k} = {${v}}`).join(',\n')}\n}`;
  }).join('\n\n') + '\n';
}

export function toRis(s) {
  return included(s).map((p) => [
    'TY  - JOUR',
    `TI  - ${p.title}`,
    ...(p.authors || []).map((a) => `AU  - ${a}`),
    p.year ? `PY  - ${p.year}` : '',
    p.venue ? `JO  - ${p.venue}` : '',
    p.doi ? `DO  - ${p.doi}` : '',
    p.url ? `UR  - ${p.url}` : '',
    p.abstract ? `AB  - ${p.abstract.replace(/\n/g, ' ')}` : '',
    'ER  - ',
  ].filter(Boolean).join('\n')).join('\n\n') + '\n';
}

export function toMarkdown(s) {
  const refs = included(s).map((p) => {
    const a = (p.authors || []);
    const authors = a.length > 6 ? a.slice(0, 6).join(', ') + ', et al.' : a.join(', ');
    const link = p.doi ? `https://doi.org/${p.doi}` : p.url;
    return `${p.n}. ${authors} (${p.year || 'n.d.'}). **${p.title}**. ${p.venue ? '*' + p.venue + '*. ' : ''}${link ? `<${link}>` : ''}`;
  });
  const a = s.audit;
  return [
    `# ${s.title || s.question}`,
    '',
    `> ${s.question}`,
    '',
    s.report || '',
    '',
    '## References',
    '',
    ...refs,
    '',
    '---',
    '',
    `*Generated by Marginalia on ${new Date(s.finishedAt || s.createdAt).toISOString().slice(0, 10)}. ${s.stats ? `${s.stats.found} papers found, ${s.stats.included} included, ${s.stats.fullText} read in full.` : ''}${a && a.score != null ? ` Citation audit: ${a.supported}/${a.checked} supported, ${a.partial} partial, ${a.unsupported} unsupported.` : ''}*`,
    '',
  ].join('\n');
}
